// Initialize Language Switcher
document.addEventListener("DOMContentLoaded", () => {
  const langButtons = document.querySelectorAll(".lang-btn");
  
  function setLanguage(lang) {
    const dict = translations[lang] || translations.en;
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");

    // Update all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    langButtons.forEach(btn => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    localStorage.setItem("verteks_lang", lang);
  }

  langButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      setLanguage(btn.getAttribute("data-lang"));
    });
  });

  const savedLang = localStorage.getItem("verteks_lang") || "en";
  setLanguage(savedLang);

  // Mobile Menu Toggle
  const mobileToggle = document.getElementById("mobileToggle");
  const navMenu = document.getElementById("navMenu");
  if (mobileToggle && navMenu) {
    mobileToggle.addEventListener("click", () => {
      navMenu.classList.toggle("open");
    });
  }

  // Quote Form to WhatsApp Submission
  const quoteForm = document.getElementById("quoteForm");
  if (quoteForm) {
    quoteForm.addEventListener("submit", (e) => {
      e.preventDefault();

      const name = document.getElementById("clientName").value.trim();
      const phone = document.getElementById("clientPhone").value.trim();
      const service = document.getElementById("serviceType").value;
      const location = document.getElementById("location").value.trim();
      const area = document.getElementById("propertyArea").value.trim();
      const urgency = document.getElementById("urgency").value;
      const notes = document.getElementById("notes").value.trim();

      const messageText = 
`🏗️ *New Site Inspection / Quotation Request*
---------------------------------------
👤 *Client Name:* ${name}
📞 *Phone / WhatsApp:* ${phone}
📍 *Property Location:* ${location}
🛠️ *Service Required:* ${service}
📐 *Estimated Area:* ${area ? area + ' m²' : 'Not specified'}
⏱️ *Timeline / Urgency:* ${urgency}
📝 *Details / Notes:* ${notes ? notes : 'None'}
---------------------------------------
_Sent via VERTEKS S.A. Construction Website_`;

      const encodedMsg = encodeURIComponent(messageText);
      const whatsappUrl = `https://wa.me/35797740923?text=${encodedMsg}`;

      window.open(whatsappUrl, "_blank");
    });
  }
});
